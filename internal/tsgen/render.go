package tsgen

import (
	"regexp"
	"strconv"
	"strings"
)

// header is the first line of every emitted file. It is the standard Go
// generated-code marker, which tooling recognises and, more usefully, which
// tells the next person reading a 700-line interface file not to edit it.
const header = "// Code generated by internal/tsgen from pkg/types/types.go. DO NOT EDIT.\n"

// RenderTypes emits the TypeScript interfaces.
//
// An array field is spelled `T[]`, not `T[] | null`, and that is the truthful
// spelling: since #151 the server never sends a list as null (see
// types.ReplaceNilSlices), so a frame that has passed the schema below holds
// an array wherever the interface says one.
func RenderTypes(model *Model) string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(`//
// The Go structs in pkg/types/types.go are the single source for everything in
// this file. To change a shape, change it there and run "make generate".

`)

	for _, enum := range model.Enums {
		writeDoc(&b, enum.Doc, "")
		b.WriteString("export type " + enum.Name + " =")
		if len(enum.Values) == 0 {
			// A named string type with no declared constants is still a string.
			b.WriteString(" string;\n\n")
			continue
		}
		for _, value := range enum.Values {
			b.WriteString("\n  | " + strconv.Quote(value))
		}
		b.WriteString(";\n\n")
	}

	for _, s := range model.Structs {
		writeDoc(&b, s.Doc, "")
		b.WriteString("export interface " + s.Name + " {\n")
		for _, f := range s.Fields {
			writeDoc(&b, f.Doc, "  ")
			name := propertyName(f.JSONName)
			if f.Optional {
				name += "?"
			}
			b.WriteString("  " + name + ": " + tsType(f) + ";\n")
		}
		b.WriteString("}\n\n")
	}

	return b.String()
}

// tsType renders a field's TypeScript type.
func tsType(f Field) string {
	out := tsShape(f.Type)
	// A pointer field is genuinely absent-or-null on the wire and the page has
	// to branch on it, so it is spelled out. A slice is not: the server
	// replaces every nil slice with an empty one before it sends it (#151).
	if f.Type.Kind != KindArray && f.Type.Nullable {
		out += " | null"
	}
	return out
}

// identifier matches a key that TypeScript accepts as a bare property name.
var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// propertyName spells a JSON key as an interface property. A key that is not
// an identifier -- "display-name" is a legal json tag -- is quoted, because a
// bare one would make the emitted file fail to compile.
func propertyName(key string) string {
	if identifier.MatchString(key) {
		return key
	}
	return strconv.Quote(key)
}

func tsShape(t Type) string {
	switch t.Kind {
	case KindObject:
		return t.Ref
	case KindArray:
		if t.Elem == nil {
			return "unknown[]"
		}
		inner := tsShape(*t.Elem)
		// A slice of pointers sends a nil element as null, and the schema
		// accepts it, so the element type says so. A slice element is never
		// itself a nil slice here: the server replaces those (#151).
		if t.Elem.Nullable && t.Elem.Kind != KindArray {
			inner += " | null"
		}
		if strings.ContainsAny(inner, " |") {
			return "(" + inner + ")[]"
		}
		return inner + "[]"
	case KindString:
		if t.Ref != "" {
			return t.Ref
		}
		return "string"
	case KindNumber:
		return "number"
	case KindBoolean:
		return "boolean"
	default:
		return "unknown"
	}
}

// RenderSchema emits the runtime schema the transport validates frames against.
//
// It is data, not code: one entry per wire type, each listing the keys that
// type declares and the shape each one has. The walk over it lives in
// $lib/schema, so the rules for what "valid" means are written once, in
// TypeScript, and this file only says what the Go types are.
func RenderSchema(model *Model) string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(`//
// The shape of every wire type, for validating a frame as it arrives.
//
// "nullable" is a fact about Go: a nil pointer marshals to JSON null, so a
// disk that is not an array sends "raid": null. Arrays are nullable here too,
// although this server never sends a null list (#151): a peer on a build from
// before that change still can during a rolling upgrade, and the schema
// describes what may arrive, not what this build sends. "optional" is
// json:",omitempty": the server may leave the key out altogether.
//
// What is done with that -- which containers the page insists on, and which
// sections it tolerates missing from an older server -- is policy and lives in
// $lib/schema, not here.

/** The shape of one value, as pkg/types declares it. */
export type FieldSchema =
  | { kind: "string"; nullable?: boolean }
  | { kind: "number"; nullable?: boolean }
  | { kind: "boolean"; nullable?: boolean }
  | { kind: "object"; ref: string; nullable?: boolean }
  | { kind: "array"; elem: FieldSchema; nullable?: boolean };

/** One key a wire type declares. */
export interface FieldEntry {
  key: string;
  type: FieldSchema;
  /** json:",omitempty" -- the server may leave the key out. */
  optional?: boolean;
}

/** Every key one wire type declares, in Go declaration order. */
export type TypeSchema = readonly FieldEntry[];

export const SCHEMA: Readonly<Record<string, TypeSchema>> = {
`)

	for _, s := range model.Structs {
		b.WriteString("  " + s.Name + ": [\n")
		for _, f := range s.Fields {
			b.WriteString("    { key: " + strconv.Quote(f.JSONName))
			if f.Optional {
				b.WriteString(", optional: true")
			}
			b.WriteString(", type: " + schemaShape(f.Type) + " },\n")
		}
		b.WriteString("  ],\n")
	}

	b.WriteString("};\n")
	return b.String()
}

func schemaShape(t Type) string {
	var parts []string
	switch t.Kind {
	case KindObject:
		parts = append(parts, `kind: "object"`, "ref: "+strconv.Quote(t.Ref))
	case KindArray:
		elem := "{ kind: \"unknown\" }"
		if t.Elem != nil {
			elem = schemaShape(*t.Elem)
		}
		parts = append(parts, `kind: "array"`, "elem: "+elem)
	case KindString:
		parts = append(parts, `kind: "string"`)
	case KindNumber:
		parts = append(parts, `kind: "number"`)
	case KindBoolean:
		parts = append(parts, `kind: "boolean"`)
	}
	if t.Nullable {
		parts = append(parts, "nullable: true")
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

// writeDoc renders a Go doc comment as JSDoc at the given indent. A one-line
// comment stays on one line, because a three-line block around six words is
// noise in a file this long.
func writeDoc(b *strings.Builder, doc, indent string) {
	if doc == "" {
		return
	}
	lines := strings.Split(strings.TrimRight(doc, "\n"), "\n")
	if len(lines) == 1 {
		b.WriteString(indent + "/** " + lines[0] + " */\n")
		return
	}
	b.WriteString(indent + "/**\n")
	for _, line := range lines {
		if line == "" {
			b.WriteString(indent + " *\n")
			continue
		}
		b.WriteString(indent + " * " + line + "\n")
	}
	b.WriteString(indent + " */\n")
}
