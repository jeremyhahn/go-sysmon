import { test, expect, type Page } from '@playwright/test';
import { applyPatch, type Patch } from '../src/lib/delta';
import { MAX_IMMEDIATE_RESYNCS } from '../src/lib/transport';
import cases from '../../../../pkg/delta/testdata/cases.json' with { type: 'json' };
import refusals from '../../../../pkg/delta/testdata/refusals.json' with { type: 'json' };
import accepted from '../../../../pkg/delta/testdata/accepted.json' with { type: 'json' };
import snapshot from './fixtures/snapshot.json' with { type: 'json' };
import { openTab } from './fixtures/tabs';

/**
 * Delta streaming.
 *
 * The stream sends what changed rather than a whole 270 kB snapshot to every
 * client on every tick. Two things have to hold, and only one is about bytes:
 *
 *  1. Applying a patch produces exactly what the server holds. src/lib/delta.ts
 *     and pkg/delta are two implementations of one format with nothing
 *     connecting them, so both are run against the same committed cases --
 *     generated by the Go differ, read here.
 *
 *  2. A frame that is missed must NEVER leave stale values rendering as
 *     current. That is the failure class of the stale peer this dashboard
 *     already guards: a frozen reading that looks measured and live. A gap has
 *     to be answered with a whole snapshot, not by applying the patch anyway
 *     and not by leaving the last one on screen.
 */

// --- 1. the format ---------------------------------------------------------

test.describe('the patch format', () => {
  test('every committed case applies exactly as the differ intended', async () => {
    expect(cases.length).toBeGreaterThan(10);
    for (const c of cases) {
      const got = applyPatch(c.before, c.patch as Patch | null);
      expect(got, `${c.name}: ${c.why}`).toEqual(c.after);
    }
  });

  test('applying a patch leaves the value it was given alone', async () => {
    // Svelte decides what to re-render by comparing object identity, so an
    // in-place mutation would update the state and repaint nothing. It would
    // also corrupt the base of every later patch.
    for (const c of cases) {
      const before = structuredClone(c.before);
      applyPatch(before, c.patch as Patch | null);
      expect(before, `${c.name} was mutated in place`).toEqual(c.before);
    }
  });

  test('every committed refusal is refused here too', async () => {
    // The negative half of the shared fixture, and it exists because this side
    // and pkg/delta drifted: the browser refused a patch naming an element the
    // array does not contain, Go applied it and returned the unchanged tree,
    // and both were "passing their tests". The positive cases had been
    // generated from one source since the format existed; the refusals were
    // written twice, by hand.
    //
    // Every case in the file has already been proved to fail in Go before it
    // was written out, so this cannot ask for a rejection the other half does
    // not make.
    //
    // A partly applied patch is the reason any of this matters: it leaves
    // numbers on screen that look measured and are not.
    expect(refusals.length).toBeGreaterThan(10);
    for (const c of refusals) {
      expect(
        () => applyPatch(c.tree, c.patch as Patch),
        `${c.name} was accepted`
      ).toThrow();
    }
  });

  test('every committed acceptance gives the same answer here', async () => {
    // Patches a receiver must handle that the DIFFER never emits, so cases.json
    // cannot hold them: it is generated from before/after pairs.
    //
    // They are about the wire rather than the format's shape -- chiefly the
    // difference between an operation field being absent and being present and
    // null. "o": null is not an operation, it is the absence of one, so a node
    // carrying it beside a real operation names one thing to do and is applied;
    // the exactly-one rule refuses two things to do, not two keys. Both sides
    // have to agree about that, and the agreement was previously assumed.
    for (const c of accepted) {
      expect(applyPatch(c.tree, c.patch as Patch), `${c.name}: ${c.why}`).toEqual(c.want);
    }
  });

  test('the browser accepts exactly the numeric identities pkg/delta does', async () => {
    // identity() runs on both sides and nothing connects them. The browser
    // rendered every parsed number with String(), so it accepted identities Go
    // refuses -- 1e16, or an unsafe integer silently rounded and then matched
    // under the rounded value -- and the two sides would then match different
    // elements while both believing they had matched.
    //
    // Asserted through applyKeyed rather than by exporting identity(), because
    // what matters is that an array carrying such a key is UNKEYABLE here just
    // as it is there.
    const refusedByGo: Array<[string, number]> = [
      ['past 2^53', 9007199254740993],
      ['sixteen digits', 1000000000000000],
      ['not an integer', 1.5],
      ['infinite', Infinity],
    ];
    for (const [name, pid] of refusedByGo) {
      expect(
        () => applyPatch([{ pid }], { a: { k: 'pid' } } as Patch),
        `${name} was accepted as an identity`
      ).toThrow();
    }

    // And the ones it does accept still work, so this refuses the unusable
    // rather than everything.
    for (const pid of [0, 1, -1, 999999999999999]) {
      expect(
        applyPatch([{ pid }], { a: { k: 'pid' } } as Patch),
        `${pid} should be a usable identity`
      ).toEqual([{ pid }]);
    }
  });

  test('a replacement with null is a change, not an absence', async () => {
    // "r" holding null and "r" being absent are the same shape to a receiver
    // that checks for undefined, and the difference is a value the dashboard
    // would go on showing after the server stopped reporting it.
    expect(applyPatch({ raid: { level: 'raid1' } }, { o: { raid: { r: null } } })).toEqual({
      raid: null,
    });
    expect(applyPatch({ raid: null }, { o: { raid: { r: { level: 'raid1' } } } })).toEqual({
      raid: { level: 'raid1' },
    });
  });
});

// --- 2. the stream ---------------------------------------------------------

/**
 * Replaces EventSource with one the test drives.
 *
 * The frames matter here, not the socket: what is under test is how the
 * transport reacts to a sequence, and Playwright's route interception cannot
 * hold a response open and push to it. The Go side covers the real socket
 * end to end.
 */
async function installFakeEventSource(page: Page) {
  await page.addInitScript(() => {
    class FakeEventSource extends EventTarget {
      static readonly CONNECTING = 0;
      static readonly OPEN = 1;
      static readonly CLOSED = 2;
      static instances: FakeEventSource[] = [];

      readonly url: string;
      readyState = FakeEventSource.OPEN;
      onopen: ((e: Event) => void) | null = null;
      onerror: ((e: Event) => void) | null = null;

      constructor(url: string) {
        super();
        this.url = url;
        FakeEventSource.instances.push(this);
        // Asynchronous, as the real one is: the caller has to have attached
        // its listeners before anything arrives.
        setTimeout(() => this.onopen?.(new Event('open')), 0);
      }

      close() {
        this.readyState = FakeEventSource.CLOSED;
      }
    }
    const w = window as unknown as { EventSource: unknown; __es: typeof FakeEventSource };
    w.EventSource = FakeEventSource;
    w.__es = FakeEventSource;
  });
}

interface FakeES {
  instances: Array<{ url: string; dispatchEvent(e: Event): boolean }>;
}

/** Pushes one frame onto the stream the page most recently opened. */
async function send(page: Page, event: string, data: unknown) {
  await page.evaluate(
    ([name, payload]) => {
      const es = (window as unknown as { __es: FakeES }).__es.instances;
      const latest = es[es.length - 1];
      latest.dispatchEvent(new MessageEvent(name as string, { data: JSON.stringify(payload) }));
    },
    [event, data] as const
  );
}

/** How many times the page has opened a stream. */
function connections(page: Page): Promise<number> {
  return page.evaluate(
    () => (window as unknown as { __es: FakeES }).__es.instances.length
  );
}

/** The URL of the most recently opened stream. */
function lastURL(page: Page): Promise<string> {
  return page.evaluate(() => {
    const es = (window as unknown as { __es: FakeES }).__es.instances;
    return es[es.length - 1]?.url ?? '';
  });
}

function snapshotWith(hostname: string) {
  return { ...snapshot, host: { ...snapshot.host, hostname } };
}

/** The hostname the Host panel is showing. */
function shownHostname(page: Page): Promise<string> {
  return page.locator('main h2').first().innerText();
}

/**
 * Puts the stream back into a known-good state AND clears the resync limiter.
 *
 * The delta is the part that is easy to leave out and impossible to notice: a
 * full frame does not clear the limiter, deliberately, because every reopened
 * stream starts with one. Only a contiguous delta that applied proves the
 * stream is carrying frames again. A test that sends the full alone drifts into
 * the backoff after three rounds and fails somewhere unrelated.
 */
async function settle(page: Page, hostname: string) {
  await send(page, 'full', { seq: 100, snapshot: snapshotWith(hostname) });
  await expect.poll(() => shownHostname(page)).toBe(hostname);
  // No patch: the tick where nothing moved. It is contiguous and it applies,
  // which is all the limiter is asking for.
  await send(page, 'delta', { seq: 101 });
}

/**
 * Payloads that are shaped like a snapshot and are not one.
 *
 * "Carries a timestamp and a host" was the first validation, and it let all of
 * these through: reported connected and current, then a throw while rendering
 * as the store reduced over an array that is not there. A frame that satisfies
 * the validator and breaks the page is a validator that moved the failure
 * rather than preventing it -- so both doors take the same list.
 *
 * Built by REMOVING one thing from a payload that does pass, so each case
 * differs from a good frame in exactly the field it names.
 */
function withoutField(field: string) {
  const partial: Record<string, unknown> = { ...snapshot };
  delete partial[field];
  return partial;
}

