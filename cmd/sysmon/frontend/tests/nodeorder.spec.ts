import { test, expect } from '@playwright/test';
import { compareNodeNames } from '../src/lib/nodeorder';
import cases from '../../../../pkg/fleet/testdata/order.json' with { type: 'json' };

/**
 * The fleet list is sorted twice — in pkg/fleet for GET /api/fleet, and here
 * for the view — and the two must produce the same order, or the API and the
 * screen disagree about what the fleet looks like.
 *
 * Nothing in either language connects them, and a disagreement is invisible:
 * both lists look sorted, and only someone comparing the API response to the
 * screen would notice they are not the same list. This ran on lowercase ASCII
 * names for weeks, which sort identically under every plausible rule, so it
 * could not see that the view used localeCompare and the backend did not.
 *
 * So both are run against one committed file, generated by the Go side.
 */
test.describe('node ordering agrees with the backend', () => {
  test('every committed case sorts identically', () => {
    expect(cases.length).toBeGreaterThan(5);
    for (const c of cases) {
      const got = [...c.input].sort(compareNodeNames);
      expect(got, `${c.name}: ${c.why}`).toEqual(c.sorted);
    }
  });

  test('localeCompare would not have passed these', () => {
    // The guard on the guard. If every case sorted the same way under
    // localeCompare, this suite would pass against the bug it exists to catch
    // — which is exactly what the previous tests did.
    const differs = cases.some((c) => {
      const byLocale = [...c.input].sort((a, b) => a.localeCompare(b));
      return JSON.stringify(byLocale) !== JSON.stringify(c.sorted);
    });
    expect(
      differs,
      'no fixture distinguishes this rule from localeCompare, so none of them proves anything'
    ).toBe(true);
  });

  test('it is a total order', () => {
    // The sort exists so the list cannot reshuffle between polls. A comparator
    // that is not antisymmetric lets it, whatever any single render looks like.
    const names = cases.flatMap((c) => c.input);
    for (const a of names) {
      expect(compareNodeNames(a, a)).toBe(0);
      for (const b of names) {
        const ab = compareNodeNames(a, b);
        const ba = compareNodeNames(b, a);
        // Summed rather than negated: Math.sign(0) is 0 and -Math.sign(0) is
        // -0, which Object.is -- and therefore toBe -- treats as different.
        expect(Math.sign(ab) + Math.sign(ba), `antisymmetry for ${a} / ${b}`).toBe(0);
      }
    }
  });
});
